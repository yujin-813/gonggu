const MAX_TAGS = 5

export function computeTags(post: Pick<Post, 'title' | 'brand' | 'cat'>): string[] {
  const cleanedTitle = cleanSearchQuery(post.title || '').toLowerCase()
  const brand = (post.brand || '').trim().toLowerCase()
  const matchText = `${cleanedTitle} ${brand}`

  const tags = new Set<string>()
  for (const [trigger, ruleTags] of Object.entries(TAG_RULES)) {
    if (matchText.includes(trigger)) {
      for (const t of ruleTags) tags.add(t)
    }
  }

  // 사전에 하나도 안 걸리면 카테고리 라벨이라도 하나 붙여서 완전히 빈 채로 두지 않는다
  if (tags.size === 0 && post.cat) {
    const label = CATEGORY_LABEL[post.cat as Category]
    if (label) tags.add(label)
  }

  // 자리가 남으면 제목의 실제 낱말을 채운다 — 사전이 못 잡아도 같은 낱말을 쓰는 다른
  // 공구끼리는 최소한 겹치게 하기 위함
  const tokens = cleanedTitle.split(/\s+/).filter(w => w.length >= 2 && w !== brand)
  for (const t of tokens) {
    if (tags.size >= MAX_TAGS) break
    tags.add(t)
  }

  return [...tags].slice(0, MAX_TAGS)
}
